#!/usr/bin/env node
/*
 * Records real consent banners as reloadable fixtures.
 *
 * The corpus exists so the detector is written against banners that exist
 * rather than banners that were imagined. Rules and heuristics written against
 * invented markup drift; written against thirty real pages they do not.
 *
 * For each site this records:
 *   profile.json — the page as the detector sees it: consent globals, what the
 *                  TCF API said about itself, and every container that looks
 *                  like an overlay, with the controls inside it. This is the
 *                  committed artefact, because it is the detector's actual
 *                  input and it is a few kilobytes rather than a megabyte.
 *   meta.json    — provenance: when, from where, which script hosts, and what
 *                  went wrong if anything did.
 *   page.html    — the whole document, shadow roots serialised declaratively
 *                  and stylesheets inlined so it renders offline. Script bodies
 *                  are stripped: a fixture must not execute, or it would
 *                  rebuild the very thing detection is being tested on. Kept
 *                  out of git — a news homepage is close to a megabyte — and
 *                  regenerated by re-running this script.
 *
 * Run with `npm run capture:fixtures`. It touches the network and real sites
 * change under it, so it is never part of `npm test`.
 */

import { mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { readFileSync } from 'node:fs';
import { PROFILE_EXPRESSION, parsePageProfile } from '../extension/src/content/page-profile.js';
import { SANDBOX_CAVEAT, launchHarness, sandboxed } from './lib/harness.mjs';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const SITES = JSON.parse(readFileSync(join(ROOT, 'tests/fixtures/sites/phase3.json'), 'utf8'));
const OUT_DIR = join(ROOT, 'tests', 'fixtures', 'banners');
const SHOT_DIR = process.env.FIXTURE_SHOT_DIR ?? null;

/** How long to give a page to render its banner before recording it. */
const SETTLE_MS = 9_000;
const NAVIGATION_TIMEOUT_MS = 30_000;

/*
 * Globals worth asking about. Presence of one of these is the strongest signal
 * a page can give about which platform is asking for consent, and it is exactly
 * what a saved HTML file cannot preserve.
 */
const CONSENT_GLOBALS = [
  '__tcfapi',
  '__cmp',
  '__gpp',
  'OneTrust',
  'OptanonWrapper',
  'Optanon',
  'Didomi',
  'didomiOnReady',
  'Cookiebot',
  'CookieConsent',
  'axeptioSDK',
  '_axcb',
  'Sirdata',
  '__uspapi',
  'UC_UI',
  'usercentrics',
  'Osano',
  'Termly',
  'Cookiehub',
  'klaro',
  'cookieconsent',
  'tarteaucitron',
  '_sp_',
  '_sp_queue',
  'consentmanager',
  'cmp_id',
  'gtag',
  'dataLayer',
];

async function record(context, site, cssByUrl) {
  const page = await context.newPage();
  cssByUrl.clear();

  page.on('response', async (response) => {
    const type = response.headers()['content-type'] ?? '';
    if (!type.includes('text/css')) return;
    try {
      cssByUrl.set(response.url(), await response.text());
    } catch {
      /* Body already gone; the fixture keeps the <link> instead. */
    }
  });

  const scriptHosts = new Set();
  page.on('request', (request) => {
    if (request.resourceType() !== 'script') return;
    try {
      scriptHosts.add(new URL(request.url()).host);
    } catch {
      /* Not a URL we can attribute. */
    }
  });

  let navigationError = null;
  try {
    await page.goto(site.url, {
      waitUntil: 'domcontentloaded',
      timeout: NAVIGATION_TIMEOUT_MS,
    });
  } catch (cause) {
    navigationError = cause.message.split('\n')[0];
  }

  await page.waitForTimeout(SETTLE_MS);

  const probe = await page
    .evaluate(async (globals) => {
      const present = globals.filter((name) => {
        try {
          return typeof globalThis[name] !== 'undefined';
        } catch {
          return false;
        }
      });

      /*
       * The TCF API names its own vendor. `cmpId` is a registered number, which
       * makes it the single most reliable identifier a page can offer.
       */
      const tcf = await new Promise((resolve) => {
        if (typeof globalThis.__tcfapi !== 'function') return resolve(null);
        const timer = setTimeout(() => resolve({ timedOut: true }), 3000);
        try {
          globalThis.__tcfapi('getTCData', 2, (data, success) => {
            clearTimeout(timer);
            resolve(
              success && data
                ? {
                    cmpId: data.cmpId ?? null,
                    cmpVersion: data.cmpVersion ?? null,
                    tcfPolicyVersion: data.tcfPolicyVersion ?? null,
                    gdprApplies: data.gdprApplies ?? null,
                    cmpStatus: data.cmpStatus ?? null,
                    eventStatus: data.eventStatus ?? null,
                  }
                : { success: false },
            );
          });
        } catch (cause) {
          clearTimeout(timer);
          resolve({ error: String(cause) });
        }
      });

      /* Every open shadow root, by a path the fixture can be checked against. */
      const shadowHosts = [];
      const walk = (root, path) => {
        for (const element of root.querySelectorAll('*')) {
          if (!element.shadowRoot) continue;
          const here = `${path} > ${element.tagName.toLowerCase()}${
            element.id ? `#${element.id}` : ''
          }`;
          shadowHosts.push(here);
          walk(element.shadowRoot, here);
        }
      };
      walk(document, ':root');

      return {
        finalUrl: location.href,
        title: document.title,
        lang: document.documentElement.lang || null,
        globals: present,
        tcf,
        shadowHosts,
        bodyChildCount: document.body ? document.body.children.length : 0,
      };
    }, CONSENT_GLOBALS)
    .catch((cause) => ({ evaluateError: cause.message.split('\n')[0] }));

  const profile = await page
    .evaluate(PROFILE_EXPRESSION)
    .then(parsePageProfile)
    .catch(() => null);

  const html = await page
    .evaluate((stylesheets) => {
      const cssMap = new Map(stylesheets);

      /* Serialise open shadow roots as declarative templates so they reload. */
      const serialiseShadow = (root) => {
        for (const element of root.querySelectorAll('*')) {
          if (!element.shadowRoot) continue;
          serialiseShadow(element.shadowRoot);
          const template = document.createElement('template');
          template.setAttribute('shadowrootmode', 'open');
          template.innerHTML = element.shadowRoot.innerHTML;
          element.prepend(template);
        }
      };

      const clone = document.documentElement.cloneNode(true);

      /*
       * Work on the clone for everything destructive. The shadow roots are the
       * exception — they are not cloned — so they are read from the live tree
       * and written into the clone by matching position.
       */
      const liveHosts = [];
      const collect = (root) => {
        for (const element of root.querySelectorAll('*')) {
          if (!element.shadowRoot) continue;
          liveHosts.push(element);
          collect(element.shadowRoot);
        }
      };
      collect(document);

      const liveAll = [...document.documentElement.querySelectorAll('*')];
      const cloneAll = [...clone.querySelectorAll('*')];
      for (const host of liveHosts) {
        const index = liveAll.indexOf(host);
        if (index === -1 || !cloneAll[index]) continue;
        const template = document.createElement('template');
        template.setAttribute('shadowrootmode', 'open');
        template.innerHTML = host.shadowRoot.innerHTML;
        cloneAll[index].prepend(template);
      }
      void serialiseShadow;

      /* A fixture must not execute. Keep the src as evidence, drop the code. */
      for (const script of clone.querySelectorAll('script')) {
        if (script.src) {
          script.setAttribute('data-fixture-src', script.src);
          script.removeAttribute('src');
        }
        script.setAttribute('type', 'application/x-fixture-inert');
        script.textContent = '';
      }

      /* Inline the stylesheets that were seen on the wire, so it renders. */
      for (const link of clone.querySelectorAll('link[rel~="stylesheet" i]')) {
        const css = cssMap.get(link.href);
        if (css === undefined) continue;
        const style = document.createElement('style');
        style.setAttribute('data-fixture-from', link.href);
        style.textContent = css;
        link.replaceWith(style);
      }

      /* Embedded binaries are most of the weight and none of the meaning. */
      for (const element of clone.querySelectorAll('[src], [href], [srcset]')) {
        for (const attribute of ['src', 'href', 'srcset']) {
          const value = element.getAttribute(attribute);
          if (value && value.startsWith('data:') && value.length > 256) {
            element.setAttribute(attribute, 'data:,fixture-stripped');
          }
        }
      }

      return `<!doctype html>\n${clone.outerHTML}`;
    }, [...cssByUrl.entries()])
    .catch(() => null);

  if (SHOT_DIR) {
    await page
      .screenshot({ path: join(SHOT_DIR, `${site.slug}.png`), fullPage: false })
      .catch(() => {});
  }

  await page.close();

  return { probe, profile, html, scriptHosts: [...scriptHosts].sort(), navigationError };
}

async function main() {
  const { context, close } = await launchHarness();
  if (SHOT_DIR) mkdirSync(SHOT_DIR, { recursive: true });

  const cssByUrl = new Map();
  const index = [];

  for (const site of SITES.sites) {
    process.stdout.write(`… ${site.slug}\n`);
    const { probe, profile, html, scriptHosts, navigationError } = await record(
      context,
      site,
      cssByUrl,
    );

    const directory = join(OUT_DIR, site.slug);
    rmSync(directory, { recursive: true, force: true });
    mkdirSync(directory, { recursive: true });

    if (html) writeFileSync(join(directory, 'page.html'), html);
    if (profile) {
      writeFileSync(join(directory, 'profile.json'), `${JSON.stringify(profile, null, 2)}\n`);
    }
    const meta = {
      slug: site.slug,
      requestedUrl: site.url,
      capturedAt: new Date().toISOString().slice(0, 10),
      navigationError,
      scriptHosts,
      ...probe,
    };
    writeFileSync(join(directory, 'meta.json'), `${JSON.stringify(meta, null, 2)}\n`);

    index.push({
      slug: site.slug,
      containers: profile ? profile.containers.length : 0,
      bytes: profile ? Buffer.byteLength(JSON.stringify(profile)) : 0,
      globals: probe?.globals ?? [],
      cmpId: probe?.tcf?.cmpId ?? null,
      error: navigationError ?? probe?.evaluateError ?? null,
    });
  }

  await close();
  report(index);
}

function report(index) {
  const lines = [
    '# Banner corpus',
    '',
    ...(sandboxed() ? [...SANDBOX_CAVEAT, ''] : []),
    '| Slug | Containers | Profile KB | TCF cmpId | Consent globals | Problem |',
    '|---|---|---|---|---|---|',
  ];
  for (const entry of index) {
    lines.push(
      `| ${entry.slug} | ${entry.containers} | ${Math.round(entry.bytes / 1024)} | ` +
        `${entry.cmpId ?? '—'} | ${entry.globals.join(' ') || '—'} | ${entry.error ?? ''} |`,
    );
  }
  const total = index.reduce((sum, entry) => sum + entry.bytes, 0);
  lines.push('', `Total ${Math.round(total / 1024)} KB of profiles across ${index.length} fixtures.`);
  process.stdout.write(`\n${lines.join('\n')}\n`);
}

await main();
